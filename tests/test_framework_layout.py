from pathlib import Path
from tempfile import TemporaryDirectory
import unittest

import yaml

from tools.apple_sdk_gen.assembler.sdk_layout import assemble_sdk
from tools.apple_sdk_gen.cli import parse_args
from tools.apple_sdk_gen.models.symbol import Symbol
from tools.apple_sdk_gen.models.types import SymbolKind


class FrameworkLayoutTest(unittest.TestCase):
    def test_macos_foundation_and_appkit_use_versioned_install_names(self):
        with TemporaryDirectory() as directory:
            for version in ("15.2", "26.5"):
                with self.subTest(version=version):
                    sdk = assemble_sdk(Path(directory), "macos", version, {"Foundation": [], "AppKit": []})
                    frameworks = sdk / "System/Library/Frameworks"
                    for name in ("Foundation", "AppKit"):
                        framework = frameworks / f"{name}.framework"
                        tbd = framework / f"{name}.tbd"
                        canonical = f"/System/Library/Frameworks/{name}.framework/Versions/C/{name}"
                        self.assertIn(f"install-name:    '{canonical}'", tbd.read_text())
                        self.assertEqual((framework / f"Versions/C/{name}.tbd").resolve(), tbd.resolve())
                    appkit = (frameworks / "AppKit.framework/AppKit.tbd").read_text()
                    self.assertIn("'/System/Library/Frameworks/Foundation.framework/Versions/C/Foundation'", appkit)

    def test_rejects_other_platforms(self):
        with TemporaryDirectory() as directory:
            with self.assertRaisesRegex(ValueError, "Unknown platform: ios"):
                assemble_sdk(Path(directory), "ios", "26.5", {})

    def test_umbrella_and_forwarding_headers_have_unique_casefolded_names(self):
        names = ["foundation", "NSString", "nsstring"]
        symbols = [
            Symbol(
                identifier=f"doc://test/documentation/foundation/{name}",
                title=name,
                kind=SymbolKind.TYPEALIAS,
            )
            for name in names
        ]
        with TemporaryDirectory() as directory:
            sdk = assemble_sdk(Path(directory), "macos", "27.0", {"Foundation": symbols})
            headers = sdk / "System/Library/Frameworks/Foundation.framework/Headers"
            self.assertEqual({p.name for p in headers.iterdir()}, {"Foundation.h", "NSString.h"})
            self.assertIn("Generated by apple-sdk-gen", (headers / "Foundation.h").read_text())
            self.assertIn("#import <Foundation/Foundation.h>", (headers / "NSString.h").read_text())

    def test_macos_assembles_cocoa_from_its_three_imports(self):
        frameworks = {name: [] for name in ("Foundation", "AppKit", "CoreData")}
        with TemporaryDirectory() as directory:
            sdk = assemble_sdk(Path(directory), "macos", "27.0", frameworks)
            root = sdk / "System/Library/Frameworks"
            cocoa = root / "Cocoa.framework"
            self.assertEqual(
                (cocoa / "Headers/Cocoa.h").read_text().splitlines(),
                [f"#import <{name}/{name}.h>" for name in frameworks],
            )
            self.assertIn('umbrella header "Cocoa.h"', (cocoa / "Modules/module.modulemap").read_text())
            stub = yaml.safe_load((cocoa / "Cocoa.tbd").read_text().removeprefix("--- !tapi-tbd\n"))
            self.assertEqual(stub["install-name"], "/System/Library/Frameworks/Cocoa.framework/Versions/A/Cocoa")
            self.assertEqual(stub["targets"], ["arm64-macos"])
            libraries = []
            for name in ("AppKit", "CoreData"):
                child = (root / f"{name}.framework/{name}.tbd").read_text()
                libraries.append(yaml.safe_load(child.removeprefix("--- !tapi-tbd\n"))["install-name"])
            self.assertEqual(stub["reexported-libraries"], [{"targets": stub["targets"], "libraries": libraries}])
            self.assertEqual(stub["exports"][0]["symbols"], ["_CocoaVersionNumber", "_CocoaVersionString"])

    def test_skips_cocoa_without_all_imports_or_when_excluded(self):
        frameworks = {name: [] for name in ("Foundation", "AppKit", "CoreData")}
        for selected, include_cocoa in (
            ({"Foundation": [], "AppKit": []}, True),
            (frameworks, False),
        ):
            with self.subTest(frameworks=selected, include_cocoa=include_cocoa):
                with TemporaryDirectory() as directory:
                    sdk = assemble_sdk(Path(directory), "macos", "27.0", selected, include_cocoa=include_cocoa)
                    self.assertFalse((sdk / "System/Library/Frameworks/Cocoa.framework").exists())

    def test_framework_selection_keeps_the_callers_list(self):
        args = parse_args(["--sdk-version", "26.5", "--frameworks", "Cocoa, AVFoundation",
                           "--llvm-dir", "llvm"])
        self.assertEqual(args.frameworks, {"Cocoa", "AVFoundation"})


if __name__ == "__main__":
    unittest.main()
